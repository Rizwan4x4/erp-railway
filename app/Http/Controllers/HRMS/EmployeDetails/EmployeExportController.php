    public function exportRegisteredEmployees()
    {
        $data = DB::connection('sqlsrv2')
            ->table('Emp_Register')
            ->get()
            ->map(function ($item) {
                return (array) $item;
            });

        $headings = array_keys((array) $data->first());

        $additionalFields = [
            'Report Title'  => 'Employee Register Export',
            'Date'          => now()->format('d-m-Y H:i'),
            'Generated By'  => auth()->user()->name ?? 'System'
        ];

        return Excel::download(
            new GeneralReportExport($data, $headings, $additionalFields),
            'employee_register_export.xlsx'
        );
    }
