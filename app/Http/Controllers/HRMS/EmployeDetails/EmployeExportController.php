    public function exportEmployees()
    {
        $data = DB::connection('sqlsrv2')->table('Emp_Profile')
            ->join('Emp_Register', 'Emp_Profile.EmployeeID', '=', 'Emp_Register.EmployeeID')
            ->select('Emp_Profile.*', 'Emp_Register.*')
            ->get()
            ->map(function ($item) {
                return (array) $item;
            });

        $headings = array_keys((array) $data->first());

        $additionalFields = [
            'Report Title' => 'Employee Full Export',
            'Date' => now()->format('d-m-Y H:i'),
            'Generated By' => auth()->user()->name ?? 'System'
        ];

        return Excel::download(new GeneralReportExport($data, $headings, $additionalFields), 'employee_full_export.xlsx');
    }
